/**
 * Stage 1 relevance check: keyword-only vs hybrid on blackbook/shortlist-benchmark.json,
 * with the Verified 4–5 rule applied. Writes blackbook/stage1-eval.md.
 */
import fs from "node:fs";
import path from "node:path";
import { repoRoot } from "../src/lib/live/paths";
import { runSearch } from "../src/lib/live/service";
import { withIndex } from "../src/lib/live/store";

interface Brief {
  id: string;
  brief: string;
  scope: "pilot" | "catalog";
  expected: { name: string; grade: number }[];
  should_not_lead: (string | { name: string })[];
}
const norm = (value: string) => value.toLowerCase().normalize("NFKD").replace(/\p{M}/gu, "").replace(/[^a-z0-9]/g, "");

async function main() {
  const benchmark = JSON.parse(fs.readFileSync(path.join(repoRoot(), "blackbook", "shortlist-benchmark.json"), "utf8"));
  const briefs: Brief[] = benchmark.briefs;
  const snapshot = await withIndex((db) =>
    db.query<{ name: string; status: string; rating: number }>("select name, status, rating from entries"),
  );
  if (!snapshot) throw new Error("No search index; run npm run sync first.");
  const { rows } = snapshot;
  const indexed = new Set(rows.map((row) => norm(row.name)));
  const lines: string[] = [];
  const summary: Record<string, { useful: number; answerable: number; noStrong: number; ineligible: number; times: number[] }> = {};
  await runSearch({ query: "warm up the model" });
  for (const mode of ["keyword", "hybrid"] as const) {
    const stats = { useful: 0, answerable: 0, noStrong: 0, ineligible: 0, times: [] as number[] };
    for (const brief of briefs) {
      const result = (await runSearch({ query: brief.brief, mode }))!;
      stats.times.push(result.ms);
      const top = result.results.slice(0, 5);
      stats.ineligible += result.results.filter((item) => item.rating !== 4 && item.rating !== 5).length;
      const eligibleExpected = brief.expected.filter((item) => item.grade >= 2 && indexed.has(norm(item.name)));
      const hit = top.some((item) => eligibleExpected.some((expected) => norm(expected.name) === norm(item.name)));
      const badLead = top[0] && brief.should_not_lead.some((item) => norm(typeof item === "string" ? item : item.name) === norm(top[0].name));
      const useful = hit && !badLead;
      const strong = result.results.filter((item) => item.tier === "strong").length;
      if (eligibleExpected.length) {
        stats.answerable++;
        if (useful) stats.useful++;
      }
      if (!strong) stats.noStrong++;
      lines.push(`| ${mode} | ${brief.id} | ${brief.scope} | ${eligibleExpected.length ? (useful ? "yes" : "**no**") : "not in rated catalog"} | ${strong} | ${top.map((item) => `${item.name}${item.tier === "weak" ? " (weak)" : ""}`).join(", ") || "none"} | ${result.ms} |`);
    }
    summary[mode] = stats;
  }
  const p95 = (times: number[]) => [...times].sort((a, b) => a - b)[Math.ceil(times.length * 0.95) - 1];
  const report = [
    "# Stage 1 relevance check",
    "",
    `Generated by \`npm run eval\` in web/ on ${new Date().toISOString().slice(0, 10)}, against the local index of Verified entries rated 4 or 5 (${rows.length} searchable entries).`,
    "A brief is answerable when at least one expected entry (grade 2 or 3) is in that index. Useful means one of them is in the top five and no should-not-lead entry is first.",
    "",
    "| Mode | Useful top five | Answerable briefs | Briefs with no strong match | Ineligible results | p95 ms |",
    "| --- | --- | --- | --- | --- | --- |",
    ...Object.entries(summary).map(([mode, stats]) => `| ${mode} | ${stats.useful} (${Math.round((100 * stats.useful) / stats.answerable)}%) | ${stats.answerable} of ${briefs.length} | ${stats.noStrong} | ${stats.ineligible} | ${p95(stats.times)} |`),
    "",
    "## Per brief",
    "",
    "| Mode | Brief | Scope | Useful | Strong | Top five | ms |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...lines,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(repoRoot(), "blackbook", "stage1-eval.md"), report);
  console.log(report.split("## Per brief")[0]);
}
main().then(() => process.exit(process.exitCode ?? 0));
